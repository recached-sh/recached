#[test]
fn a_frame_is_one_allocation_of_its_exact_size() {
    let value = [b'x'; 32];
    let parts: [&[u8]; 3] = [b"SET", b"key:000000042", &value];
    let (frame, allocs) = allocations_in(|| resp_push(&parts));
    assert_eq!(allocs, 1, "resp_push allocated {allocs} times");
    assert_eq!(
        frame.capacity(),
        frame.len(),
        "capacity is the exact length"
    );

    // The hot arms add nothing beyond the frame itself, except the parts
    // list of a variadic command (one `Vec` of borrowed slices).
    let ok = Value::SimpleString("OK".into());
    let set = Command::Set("k".into(), value.to_vec(), SetOptions::default());
    let (_, allocs) = allocations_in(|| broadcast_for(&set, &ok, NOW));
    assert_eq!(allocs, 1, "SET");
    let incr = Command::Incr("k".into());
    let (_, allocs) = allocations_in(|| broadcast_for(&incr, &Value::Integer(-12_345), NOW));
    assert_eq!(allocs, 1, "INCR");
    let hset = Command::HSet("h".into(), vec![("f".into(), value.to_vec())]);
    let (_, allocs) = allocations_in(|| broadcast_for(&hset, &Value::Integer(1), NOW));
    assert_eq!(allocs, 2, "HSET");
    let mset = Command::MSet(vec![
        ("a".into(), value.to_vec()),
        ("b".into(), value.to_vec()),
    ]);
    let (_, allocs) = allocations_in(|| broadcast_for(&mset, &ok, NOW));
    assert_eq!(allocs, 2, "MSET");
}
