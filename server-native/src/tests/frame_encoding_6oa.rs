fn command(args: &[Vec<u8>]) -> Command {
    let v = Value::Array(Some(
        args.iter()
            .map(|a| Value::BulkString(Some(a.clone())))
            .collect(),
    ));
    Command::from_value(v)
        .unwrap_or_else(|e| panic!("{:?}: {e}", String::from_utf8_lossy(&args[0])))
}

/// What each command of the script propagates, run against a real store in
/// order: its frame, or `None` when it builds none.
fn script_outcomes() -> Vec<Option<Vec<u8>>> {
    let store = KeyValueStore::new();
    script()
        .iter()
        .map(|args| {
            let cmd = command(args);
            let (response, _) = store.execute_reporting_ref(&cmd);
            broadcast_for_at(&cmd, &response, NOW, None)
        })
        .collect()
}

/// The fixture's bytes: per command `#<n> ` then the frame, or `-` when it
/// builds none; then the DEDUP and checkpoint records the AOF writes
/// alongside.
fn script_frames() -> Vec<u8> {
    let outcomes = script_outcomes();
    let mut out = Vec::new();
    for (i, frame) in outcomes.iter().enumerate() {
        out.extend_from_slice(format!("#{i} ").as_bytes());
        out.extend_from_slice(frame.as_deref().unwrap_or(b"-\r\n"));
    }
    let set = outcomes
        .iter()
        .flatten()
        .find(|f| f.starts_with(b">3\r\n$3\r\nSET\r\n"))
        .expect("the script sets a key");
    // The branches that take the deadline the store set (`exact_deadline`)
    // rather than computing one from the clock.
    let deadline = Some(NOW + 12_345);
    let ok = Value::SimpleString("OK".into());
    let hit = Value::BulkString(Some(b"v".to_vec()));
    let ex = SetOptions {
        expiry: Some(SetExpiry::Ex(10)),
        ..Default::default()
    };
    let px = SetOptions {
        expiry: Some(SetExpiry::Px(10)),
        ..Default::default()
    };
    for (cmd, response) in [
        (Command::Set("dk".into(), b"v".to_vec(), ex), ok.clone()),
        (Command::Set("dk".into(), b"v".to_vec(), px), ok.clone()),
        (Command::SetEx("dk".into(), 10, b"v".to_vec()), ok.clone()),
        (Command::PSetEx("dk".into(), 10, b"v".to_vec()), ok),
        (Command::Expire("dk".into(), 10), Value::Integer(1)),
        (Command::PExpire("dk".into(), 10), Value::Integer(1)),
        (
            Command::GetEx("dk".into(), Some(GetExOption::Ex(10))),
            hit.clone(),
        ),
        (Command::GetEx("dk".into(), Some(GetExOption::Px(10))), hit),
    ] {
        out.extend_from_slice(b"#d ");
        let frame = broadcast_for_at(&cmd, &response, NOW, deadline);
        out.extend_from_slice(frame.as_deref().unwrap_or(b"-\r\n"));
    }
    for record in [
        dedup_wrap("client-a", 42, set),
        dedup_wrap("", u64::MAX, set),
        dedup_mark_frame("client-a", 0),
        dedup_refusal_frame("client-b", 7, "ERR value is not an integer or out of range"),
        checkpoint_frame(0),
        checkpoint_frame(u64::MAX),
    ] {
        out.extend_from_slice(b"#x ");
        out.extend_from_slice(&record);
    }
    out
}

#[test]
fn frames_match_the_baseline_build() {
    let got = script_frames();
    if std::env::var_os("RECACHED_WRITE_FRAME_FIXTURE").is_some() {
        std::fs::write(FIXTURE, &got).expect("write the fixture");
        // Never a silent pass: a regenerated fixture compares this build
        // with itself. Regenerate only on the baseline build, then commit.
        panic!(
            "fixture regenerated from this build ({} bytes); unset RECACHED_WRITE_FRAME_FIXTURE",
            got.len()
        );
    }
    let want = std::fs::read(FIXTURE).expect("the baseline fixture");
    if got != want {
        let at = got
            .iter()
            .zip(&want)
            .position(|(a, b)| a != b)
            .unwrap_or(got.len().min(want.len()));
        let from = at.saturating_sub(80);
        panic!(
            "frames differ from the a697f54 baseline at byte {at} (got {} bytes, want {}):\n got: {:?}\nwant: {:?}",
            got.len(),
            want.len(),
            String::from_utf8_lossy(&got[from..(at + 80).min(got.len())]),
            String::from_utf8_lossy(&want[from..(at + 80).min(want.len())]),
        );
    }
}

/// The fixture is the frames of a real store's responses: the script must
/// exercise what it claims, or a broken arm could hide behind a `-`. These
/// are the commands that build no frame, each on purpose: a failed
/// condition, a missing key or field, an overflow, a type error, and the
/// DEDUP-wrapped writes (the connection unwraps those before propagation;
/// their envelope is the `dedup_wrap` record).
#[test]
fn the_fixture_script_builds_frames() {
    let none: Vec<String> = script()
        .iter()
        .zip(script_outcomes())
        .filter(|(_, frame)| frame.is_none())
        .map(|(args, _)| {
            args.iter()
                .map(|a| String::from_utf8_lossy(a).into_owned())
                .collect::<Vec<_>>()
                .join(" ")
        })
        .collect();
    let expected = [
        "SET s nx NX",
        "SET absent xx XX",
        "SETNX s no",
        "INCR n",
        "INCR s",
        "EXPIRE absent 100",
        "PERSIST s",
        "GETDEL m3",
        "RENAMENX m2b fresh",
        "HDEL h nope",
        "HSETNX h f1 no",
        "LPUSHX absent lx",
        "SADD st a",
        "DEDUP client-a 42 INCRBY dd 2",
        "DEDUP client-a 43 SET ds v EX 10",
    ];
    assert_eq!(none, expected);
}

