//! 6O-A: the bytes of every propagated write frame, pinned.
//!
//! `resp_push` and the `broadcast_for_at` arms for `HSET`, `MSET` and the
//! counters were rewritten to allocate less (6O-A). What they build is the
//! one buffer the AOF, every replica and every browser receive, and an AOF
//! written by any earlier build must still replay, so not one byte may change.
//! Three independent checks hold them to that:
//!
//! - [`reference_resp_push`] is the encoder as it was before 6O-A, kept
//!   verbatim. Generated inputs must encode identically: part counts and
//!   lengths on both sides of every decimal-digit boundary, empty parts,
//!   binary with embedded CRLF and RESP markers, and a 1 MiB part.
//! - `fixtures/broadcast-6oa-baseline.bin` holds every frame a fixed script
//!   of writes (every `broadcast_for_at` arm the script can reach, the
//!   stored-deadline branches, DEDUP envelopes, marks, refusals and
//!   checkpoints) produced on `dev`
//!   `a697f54`, before the change. It was generated by this file on that
//!   build with `RECACHED_WRITE_FRAME_FIXTURE=1`, and is compared byte for
//!   byte here.
//! - A few frames written out by hand.
//!
//! And the reason for the change: building a frame allocates exactly once,
//! its exact size, with no reallocation.

use super::request_path::allocations_in;
use crate::*;

/// `resp_push` before 6O-A, verbatim: a `format!` per header, growing as it goes.
fn reference_resp_push(parts: &[&[u8]]) -> Vec<u8> {
    let mut out = format!(">{}\r\n", parts.len()).into_bytes();
    for part in parts {
        out.extend_from_slice(format!("${}\r\n", part.len()).as_bytes());
        out.extend_from_slice(part);
        out.extend_from_slice(b"\r\n");
    }
    out
}

/// Deterministic bytes, binary and textual alike.
fn bytes(seed: u64, len: usize) -> Vec<u8> {
    let mut state = seed | 1;
    (0..len)
        .map(|_| {
            state ^= state << 13;
            state ^= state >> 7;
            state ^= state << 17;
            // Bias toward the bytes a RESP encoder must pass through untouched.
            match state % 8 {
                0 => b'\r',
                1 => b'\n',
                2 => b'$',
                3 => b'>',
                _ => (state >> 8) as u8,
            }
        })
        .collect()
}

#[test]
fn resp_push_matches_the_original_encoder() {
    // Lengths on both sides of every digit boundary up to 100,000.
    let mut lengths = vec![0usize, 1, 2];
    for p in [10usize, 100, 1_000, 10_000, 100_000] {
        lengths.extend([p - 1, p, p + 1]);
    }
    for (i, &len) in lengths.iter().enumerate() {
        let part = bytes(i as u64, len);
        let parts: [&[u8]; 3] = [b"SET", b"k", &part];
        assert_eq!(
            resp_push(&parts),
            reference_resp_push(&parts),
            "a {len}-byte part"
        );
    }
    // Part counts across the digit boundaries, every part a different length.
    for count in [0usize, 1, 2, 9, 10, 11, 99, 100, 101, 999, 1_000, 1_001] {
        let owned: Vec<Vec<u8>> = (0..count)
            .map(|i| bytes(1_000 + i as u64, i % 37))
            .collect();
        let parts: Vec<&[u8]> = owned.iter().map(Vec::as_slice).collect();
        assert_eq!(
            resp_push(&parts),
            reference_resp_push(&parts),
            "{count} parts"
        );
    }
    // Empty and degenerate parts, and a 1 MiB value.
    let big = bytes(7, 1 << 20);
    for parts in [
        vec![&b""[..]],
        vec![&b""[..], &b""[..], &b""[..]],
        vec![&b"\r\n"[..], &b"$-1\r\n"[..], &b">3\r\n"[..]],
        vec![&b"SET"[..], &b"big"[..], &big[..]],
    ] {
        let got = resp_push(&parts);
        assert_eq!(got, reference_resp_push(&parts));
        assert_eq!(got.capacity(), got.len());
    }
}

#[test]
fn hand_written_frames() {
    let set = Command::Set("key:000042".into(), b"v".to_vec(), SetOptions::default());
    assert_eq!(
        broadcast_for(&set, &Value::SimpleString("OK".into()), 0).unwrap(),
        b">3\r\n$3\r\nSET\r\n$10\r\nkey:000042\r\n$1\r\nv\r\n"
    );
    let incr = Command::Incr("n".into());
    assert_eq!(
        broadcast_for(&incr, &Value::Integer(i64::MIN), 0).unwrap(),
        b">4\r\n$3\r\nSET\r\n$1\r\nn\r\n$20\r\n-9223372036854775808\r\n$7\r\nKEEPTTL\r\n"
    );
    assert_eq!(
        broadcast_for(&incr, &Value::Integer(0), 0).unwrap(),
        b">4\r\n$3\r\nSET\r\n$1\r\nn\r\n$1\r\n0\r\n$7\r\nKEEPTTL\r\n"
    );
    let hset = Command::HSet(
        "h".into(),
        vec![("f".into(), b"".to_vec()), ("g".into(), b"\r\n".to_vec())],
    );
    assert_eq!(
        broadcast_for(&hset, &Value::Integer(2), 0).unwrap(),
        b">6\r\n$4\r\nHSET\r\n$1\r\nh\r\n$1\r\nf\r\n$0\r\n\r\n$1\r\ng\r\n$2\r\n\r\n\r\n"
    );
    let mset = Command::MSet(vec![
        ("a".into(), b"1".to_vec()),
        ("b".into(), b"".to_vec()),
    ]);
    assert_eq!(
        broadcast_for(&mset, &Value::SimpleString("OK".into()), 0).unwrap(),
        b">5\r\n$4\r\nMSET\r\n$1\r\na\r\n$1\r\n1\r\n$1\r\nb\r\n$0\r\n\r\n"
    );
}

