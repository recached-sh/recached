//! The command catalog — what `COMMAND`, `COMMAND INFO`, `COMMAND COUNT`,
//! `COMMAND LIST` and `COMMAND DOCS` report.
//!
//! Arity, flags and key positions are transcribed from a real `redis-server`
//! 7.2.5's own `COMMAND INFO`, not written from memory. Clients and proxies
//! route on those numbers — a wrong `first_key` sends a command to the wrong
//! shard, and a wrong arity makes a client reject a call the server would have
//! accepted — so the reference implementation is the only honest source. The
//! commands Recached invents have no Redis entry and are declared here
//! directly.
//!
//! Summaries come from `docs/server/commands.md`, so the text a client sees is
//! the text that was reviewed and published rather than a second description
//! that can drift away from it.

/// One row of the catalog. Mirrors the fields `COMMAND INFO` returns, in order.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CommandSpec {
    /// Lowercase, as Redis reports it.
    pub name: &'static str,
    /// Total argument count including the command name. Negative means "at
    /// least this many", the Redis convention.
    pub arity: i32,
    pub flags: &'static [&'static str],
    /// 1-based position of the first key argument, or 0 for keyless commands.
    pub first_key: i32,
    /// Position of the last key argument; -1 means "to the end".
    pub last_key: i32,
    /// Stride between key positions.
    pub step: i32,
    /// Section of the command reference this belongs to.
    pub group: &'static str,
    /// One-line description, for `COMMAND DOCS`.
    pub summary: &'static str,
}

#[allow(clippy::too_many_arguments)]
const fn spec(
    name: &'static str,
    arity: i32,
    flags: &'static [&'static str],
    first_key: i32,
    last_key: i32,
    step: i32,
    group: &'static str,
    summary: &'static str,
) -> CommandSpec {
    CommandSpec {
        name,
        arity,
        flags,
        first_key,
        last_key,
        step,
        group,
        summary,
    }
}

