/// Look a command up by name, case-insensitively. Returns `None` for anything
/// the parser would answer `unknown command` to.
pub fn lookup(name: &str) -> Option<&'static CommandSpec> {
    CATALOG.iter().find(|c| c.name.eq_ignore_ascii_case(name))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cmd::Command;
    use crate::resp::Value;

    /// Every catalog row must name a command the parser actually accepts.
    ///
    /// The reverse direction — every command the parser accepts has a row — is
    /// checked in the server by `every_command_is_in_the_catalog`, which walks
    /// the exhaustive `Command` variant table. Together they close the loop: a
    /// command cannot be added, removed or renamed without one of them failing.
    #[test]
    fn catalog_names_are_real_commands() {
        for spec in CATALOG {
            let frame = Value::Array(Some(vec![Value::BulkString(Some(
                spec.name.as_bytes().to_vec(),
            ))]));
            // Parsing bare `NAME` either succeeds or fails on arity; what it
            // must never do is fall through to Unknown, which is what the
            // server answers `unknown command` to.
            if let Ok(Command::Unknown(_)) = Command::from_value(frame) {
                panic!(
                    "catalog lists '{}', which the parser does not know",
                    spec.name
                );
            }
        }
    }

    #[test]
    fn catalog_has_no_duplicate_names() {
        let mut names: Vec<&str> = CATALOG.iter().map(|c| c.name).collect();
        names.sort_unstable();
        let before = names.len();
        names.dedup();
        assert_eq!(before, names.len(), "a command is listed twice");
    }

    #[test]
    fn catalog_names_are_lowercase() {
        // Redis reports lowercase names, and clients index the COMMAND DOCS
        // map by exactly the string they get back.
        for spec in CATALOG {
            assert_eq!(spec.name, spec.name.to_lowercase(), "{}", spec.name);
        }
    }

    #[test]
    fn every_command_has_a_summary() {
        for spec in CATALOG {
            assert!(
                !spec.summary.is_empty(),
                "{} has no summary, so COMMAND DOCS would describe it as nothing",
                spec.name
            );
            assert!(!spec.group.is_empty(), "{} has no group", spec.name);
        }
    }

    #[test]
    fn key_positions_agree_with_arity() {
        for spec in CATALOG {
            if spec.first_key == 0 {
                assert_eq!(
                    spec.step, 0,
                    "{} claims no keys but a non-zero step",
                    spec.name
                );
                continue;
            }
            assert!(spec.step >= 1, "{} has keys but no stride", spec.name);
            // A command whose first key sits at position N needs at least N+1
            // arguments including its own name.
            let min_args = spec.arity.abs();
            assert!(
                min_args > spec.first_key,
                "{}: first key at {} but arity is {}",
                spec.name,
                spec.first_key,
                spec.arity
            );
        }
    }

    #[test]
    fn lookup_is_case_insensitive() {
        assert_eq!(lookup("GET").map(|c| c.name), Some("get"));
        assert_eq!(lookup("HsCaN").map(|c| c.name), Some("hscan"));
        assert!(lookup("nosuchcommand").is_none());
    }
}
